const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const support = fs.readFileSync(path.join(root, 'settings/features/options-diagnostics.js'), 'utf8');
const main = fs.readFileSync(path.join(root, 'content/main.js'), 'utf8');
const options = fs.readFileSync(path.join(root, 'options.html'), 'utf8');
const start = support.indexOf('function supportIncludeFeatureNames()');
const end = support.indexOf('async function copyDiagnostics(', start);
assert(start >= 0 && end > start);
const ctx = vm.createContext({document:{querySelector:()=>null,querySelectorAll:()=>[]}});
vm.runInContext(support.slice(start, end), ctx);
assert.equal(vm.runInContext('supportIncludeFeatureNames()', ctx), false);
const sample = ['enableContextKeeper', 'enablePersonaOrganizer', 'showQuickPanel', 'blockCards', 'lorebookEntryCopyButton', 'saiToolkitCompatibility'];
const counts = vm.runInContext('supportFeatureCounts('+JSON.stringify(sample)+')', ctx);
assert.equal(counts.split('; ').reduce((n,item)=>n+Number(item.split(' ').at(-1)),0),sample.length);
const input = 'user bot https://spicychat.ai/chat/88bd19be-49ee-455f-b47e-dc0f48d6c601/76963f0f-d837-4476-80cd-bea25c324b82 email x@foo.com; "sessionId":"f72b8c81-f01f-46ba-a84a-df49b38fb149"; authorization:Bearer abcd.abc.abc; x-guest-userid: deadbeef';
const redacted=vm.runInContext('sanitizeSupportReportText('+JSON.stringify(input)+')',ctx);
for (const hidden of ['spicychat.ai/chat','88bd19be','76963f0f','foo.com','f72b8c81','abcd.abc','deadbeef']) assert(!redacted.includes(hidden),`leaked ${hidden}: ${redacted}`);
assert(support.includes('QoL runtime log: ${runtimeLog.length} events (only category and severity totals'), 'log should be categorized, not raw');
assert(!support.includes('diagnosticLines.push(`  ${when} [${entry?.level || "info"}]'), 'raw log output still enabled');
assert.equal((options.match(/data-ds-support-feature-names/g) || []).length,2);
assert(main.includes('DS.state.nativeActionQuietUntil = Date.now() + 1100'));
assert(main.includes('slowDelay = Math.max(slowDelay, Number(DS.state.nativeActionQuietUntil) - Date.now() + 180)'));
assert(main.includes('durationThreshold: 64'));
// Evaluate the actual native pointerdown handler with a minimal fake DOM and state.
const open=main.indexOf('// Protect native Regenerate/Send interactions');
const close=main.indexOf('// Event Timing reveals actual input delay.',open);
assert(open>=0 && close>open);
let pointerHandler;
const stats={};
const DS={state:{settings:{enabled:true}},isSingleChatPage:()=>true};
vm.runInNewContext(main.slice(open,close), {document:{addEventListener:(type,cb,opts)=>{if(type==='pointerdown'){pointerHandler=cb;assert(opts.capture&&opts.passive);}}},DS,runtimeCounters:()=>stats,Date});
const makeEvent = (label,qol)=>({target:{closest:()=>({getAttribute:k=>k==='aria-label'?label:'', textContent:label,matches:()=>qol,closest:()=>null})}});
assert(pointerHandler);
pointerHandler(makeEvent('Regenerate',false));
assert(DS.state.nativeActionQuietUntil>Date.now());
assert.equal(stats.nativeActionGuardStarts,1);
DS.state.nativeActionQuietUntil=0;
pointerHandler(makeEvent('Go to reply',false));
assert.equal(DS.state.nativeActionQuietUntil,0);
pointerHandler(makeEvent('Regenerate',true));
assert.equal(stats.nativeActionGuardStarts,1);
console.log('Support privacy redaction, feature summary/opt-in, and native-action guard tests passed.');
